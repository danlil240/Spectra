#!/usr/bin/env python3
"""Generate src/core/colormap_tables.hpp from matplotlib's colormaps.

Every built-in Spectra colormap is a 256-entry RGB8 lookup table: entry i is
matplotlib's colormap resampled to 256 entries, cmap.resampled(256)(i).  A
value t in [0, 1] reads entry min(int(t * 256), 255), the same nearest-entry
rule matplotlib uses, so Spectra and matplotlib show the same colour for the
same t (up to 8-bit rounding).

Usage (needs matplotlib; any recent version, the tables are stable):
    python3 -m venv /tmp/mpl && /tmp/mpl/bin/pip install matplotlib
    /tmp/mpl/bin/python tools/gen_colormap_tables.py [output.hpp]

Licenses: see licenses/matplotlib-LICENSE.txt (viridis family CC0, turbo
Apache-2.0, RdBu/PuOr ColorBrewer Apache-2.0, the rest matplotlib's license).
"""

import pathlib
import sys

import matplotlib
import numpy as np

# (C++ table name, matplotlib name).  Order is free; the ColormapType <-> table
# mapping lives in src/core/colormap.cpp.
MAPS = [
    ("VIRIDIS", "viridis"),
    ("PLASMA", "plasma"),
    ("INFERNO", "inferno"),
    ("MAGMA", "magma"),
    ("JET", "jet"),
    ("COOLWARM", "coolwarm"),
    ("GRAY", "gray"),
    ("CIVIDIS", "cividis"),
    ("TURBO", "turbo"),
    ("TWILIGHT", "twilight"),
    ("RDBU", "RdBu"),
    ("PUOR", "PuOr"),
    ("HOT", "hot"),
]

LUT_SIZE = 256
PER_LINE = 6


def table(name):
    cmap = matplotlib.colormaps[name].resampled(LUT_SIZE)
    rgba = cmap(np.arange(LUT_SIZE))
    rgb8 = np.clip(np.rint(rgba[:, :3] * 255.0), 0, 255).astype(int)
    return [tuple(int(c) for c in row) for row in rgb8]


def main():
    root = pathlib.Path(__file__).resolve().parent.parent
    out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "src/core/colormap_tables.hpp"

    lines = [
        "#pragma once",
        "",
        "// GENERATED by tools/gen_colormap_tables.py from matplotlib "
        f"{matplotlib.__version__} -- do not edit.",
        "//",
        "// 256-entry RGB8 lookup tables, one per built-in colormap: entry i is",
        "// matplotlib's cmap.resampled(256)(i).  A value t in [0, 1] reads entry",
        "// min(int(t * 256), 255), as matplotlib does.  Licenses of the colormap data:",
        "// licenses/matplotlib-LICENSE.txt.",
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace spectra::colormap_tables",
        "{",
        "",
        f"inline constexpr size_t LUT_SIZE = {LUT_SIZE};",
        "",
        "using Rgb8 = std::array<uint8_t, 3>;",
        "using Lut  = std::array<Rgb8, LUT_SIZE>;",
        "",
        "// clang-format off",
    ]
    for cxx_name, mpl_name in MAPS:
        entries = table(mpl_name)
        lines.append(f"// matplotlib '{mpl_name}'")
        lines.append(f"inline constexpr Lut {cxx_name} = {{{{")
        for i in range(0, LUT_SIZE, PER_LINE):
            chunk = entries[i:i + PER_LINE]
            lines.append("    " + " ".join(f"{{{r:3d}, {g:3d}, {b:3d}}}," for r, g, b in chunk))
        lines.append("}};")
        lines.append("")
    lines[-1:] = ["// clang-format on", "", "}   // namespace spectra::colormap_tables", ""]
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
