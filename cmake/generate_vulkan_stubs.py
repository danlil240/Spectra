#!/usr/bin/env python3
"""Generate no-op definitions for every Vulkan core entry point (plus GLFW's
two Vulkan helpers).

Used by Emscripten builds: browsers have no Vulkan, but App code still links
against the Vulkan backend.  Each stub fails (VK_ERROR_INITIALIZATION_FAILED)
or returns a zero value, so the Vulkan backend reports an init error instead of
the link failing.

usage: generate_vulkan_stubs.py <vulkan_core.h> <output.cpp>
"""

import re
import sys

PROTO_RE = re.compile(r"VKAPI_ATTR\s+(.+?)\s+VKAPI_CALL\s+(vk\w+)\s*\((.*?)\);", re.DOTALL)


def main() -> int:
    header_path, out_path = sys.argv[1], sys.argv[2]
    with open(header_path, encoding="utf-8") as f:
        header = f.read()

    seen = set()
    lines = [
        "// Generated by cmake/generate_vulkan_stubs.py — do not edit.",
        "#include <type_traits>",
        "#include <vulkan/vulkan_core.h>",
        "",
        "namespace",
        "{",
        "template <class R>",
        "R spectra_vk_stub()",
        "{",
        "    if constexpr (std::is_same_v<R, VkResult>)",
        "        return VK_ERROR_INITIALIZATION_FAILED;",
        "    else if constexpr (!std::is_void_v<R>)",
        "        return R{};",
        "}",
        "}   // namespace",
        "",
        'extern "C"',
        "{",
    ]
    for ret, name, params in PROTO_RE.findall(header):
        if name in seen:
            continue
        seen.add(name)
        params = " ".join(params.split())
        lines.append(f"{ret} VKAPI_CALL {name}({params}) {{ return spectra_vk_stub<{ret}>(); }}")
    # Emscripten's browser GLFW has no Vulkan surface support either.
    lines += [
        "struct GLFWwindow;",
        "VkResult glfwCreateWindowSurface(VkInstance, GLFWwindow*, const VkAllocationCallbacks*,",
        "                                 VkSurfaceKHR*)",
        "{",
        "    return VK_ERROR_INITIALIZATION_FAILED;",
        "}",
        "int glfwGetPhysicalDevicePresentationSupport(VkInstance, VkPhysicalDevice, uint32_t)",
        "{",
        "    return 0;",
        "}",
        "}",
    ]

    if not seen:
        print(f"no Vulkan prototypes found in {header_path}", file=sys.stderr)
        return 1
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
